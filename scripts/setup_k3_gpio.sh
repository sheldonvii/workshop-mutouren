#!/usr/bin/env bash
# 配置 K3 GPIO 权限：让普通用户无需 sudo 即可用 GPIO 软件脉冲驱动舵机。
#
# 用法：
#   sudo ./scripts/setup_k3_gpio.sh               安装，可重复执行
#   ./scripts/setup_k3_gpio.sh --check            只检查，不改动，不需要 sudo
#   sudo ./scripts/setup_k3_gpio.sh --uninstall   撤销
#   --user NAME                                   授权给指定用户，默认是调用 sudo 的用户
#
# 安装内容：
#   1. 系统组 gpio（udev 只接受系统组，GID 小于 1000 的组）
#   2. 把用户加入 gpio 组
#   3. udev 规则：K3 SoC GPIO 控制器下的 gpiochip 归 gpio 组、权限 0660；EC 的 gpiochip 不受影响
#   4. 实时调度限额：gpio 组成员可使用 SCHED_FIFO，舵机脉冲时序才稳定
set -euo pipefail

GROUP=gpio
CONTROLLER=d4019000.gpio
RTPRIO=80
RULE_FILE=/etc/udev/rules.d/60-k3-gpio.rules
LIMITS_FILE=/etc/security/limits.d/60-gpio-rtprio.conf

RULE_LINE="SUBSYSTEM==\"gpio\", KERNEL==\"gpiochip*\", KERNELS==\"$CONTROLLER\", GROUP=\"$GROUP\", MODE=\"0660\""
LIMITS_LINE="@$GROUP - rtprio $RTPRIO"

ok()   { printf '  [通过] %s\n' "$*"; }
bad()  { printf '  [缺失] %s\n' "$*"; }
info() { printf '%s\n' "$*"; }
die()  { printf '错误：%s\n' "$*" >&2; exit 1; }

sys_gid_max() {
    local max
    max=$(awk '$1 == "SYS_GID_MAX" {print $2}' /etc/login.defs 2>/dev/null || true)
    echo "${max:-999}"
}

group_gid() { getent group "$GROUP" | cut -d: -f3; }

group_members() { getent group "$GROUP" | cut -d: -f4 | tr ',' ' '; }

user_in_group() {
    local member
    for member in $(group_members); do
        [ "$member" = "$TARGET_USER" ] && return 0
    done
    return 1
}

effective_lines() { [ -f "$1" ] && grep -v -e '^[[:space:]]*#' -e '^[[:space:]]*$' "$1" || true; }

controller_chips() {
    local dev path
    for dev in /dev/gpiochip*; do
        [ -e "$dev" ] || continue
        path=$(udevadm info -q path -n "$dev" 2>/dev/null || true)
        case "$path" in *"/$CONTROLLER/"*) echo "$dev" ;; esac
    done
}

check() {
    local failed=0 gid chips dev
    info "检查 GPIO 权限配置（用户 $TARGET_USER）"

    if [ -e "/sys/bus/platform/devices/$CONTROLLER" ]; then
        ok "GPIO 控制器 $CONTROLLER 存在"
    else
        bad "没有找到 GPIO 控制器 $CONTROLLER，这块板子可能不是 K3"; failed=1
    fi

    gid=$(group_gid)
    if [ -z "$gid" ]; then
        bad "组 $GROUP 不存在"; failed=1
    elif [ "$gid" -gt "$(sys_gid_max)" ]; then
        bad "组 $GROUP 的 GID 为 $gid，不是系统组，udev 会忽略"; failed=1
    else
        ok "系统组 $GROUP（GID $gid）"
    fi

    if [ -n "$gid" ] && user_in_group; then
        ok "$TARGET_USER 已在 $GROUP 组"
    else
        bad "$TARGET_USER 不在 $GROUP 组"; failed=1
    fi

    if [ "$(effective_lines "$RULE_FILE")" = "$RULE_LINE" ]; then
        ok "udev 规则 $RULE_FILE"
    else
        bad "udev 规则 $RULE_FILE 不存在或内容不符"; failed=1
    fi

    if [ "$(effective_lines "$LIMITS_FILE")" = "$LIMITS_LINE" ]; then
        ok "实时调度限额 $LIMITS_FILE"
    else
        bad "实时调度限额 $LIMITS_FILE 不存在或内容不符"; failed=1
    fi

    chips=$(controller_chips)
    if [ -z "$chips" ]; then
        bad "没有找到 $CONTROLLER 下的 /dev/gpiochip*"; failed=1
    fi
    for dev in $chips; do
        if [ "$(stat -c '%G %a' "$dev")" = "$GROUP 660" ]; then
            ok "$dev 归 $GROUP 组、权限 660"
        else
            bad "$dev 当前为 $(stat -c '%U:%G %a' "$dev")"; failed=1
        fi
    done

    if [ "$failed" -eq 0 ]; then
        info "全部通过。$TARGET_USER 新登录的会话可直接运行舵机程序，无需 sudo。"
    else
        info "有缺失项，执行：sudo $0"
    fi
    return "$failed"
}

ensure_system_group() {
    local gid members primary_users
    gid=$(group_gid)
    if [ -z "$gid" ]; then
        groupadd --system "$GROUP"
        info "已创建系统组 $GROUP（GID $(group_gid)）"
        return
    fi
    if [ "$gid" -le "$(sys_gid_max)" ]; then
        info "系统组 $GROUP 已存在（GID $gid）"
        return
    fi
    primary_users=$(awk -F: -v g="$gid" '$4 == g {print $1}' /etc/passwd)
    [ -z "$primary_users" ] || die "组 $GROUP（GID $gid）是 $primary_users 的主组，无法自动重建，请手动处理"
    members=$(group_members)
    groupdel "$GROUP"
    groupadd --system "$GROUP"
    for member in $members; do usermod -aG "$GROUP" "$member"; done
    info "组 $GROUP 原为普通组（GID $gid），已重建为系统组（GID $(group_gid)），原成员已加回：${members:-无}"
}

install() {
    [ "$(id -u)" -eq 0 ] || die "安装需要 root：sudo $0"
    [ -e "/sys/bus/platform/devices/$CONTROLLER" ] || die "没有找到 GPIO 控制器 $CONTROLLER"
    id "$TARGET_USER" >/dev/null 2>&1 || die "用户 $TARGET_USER 不存在"

    ensure_system_group
    usermod -aG "$GROUP" "$TARGET_USER"
    info "已把 $TARGET_USER 加入 $GROUP 组"

    printf '# Generated by setup_k3_gpio.sh: SoC GPIO chips under %s -> group %s; EC gpiochip is not affected\n%s\n' \
        "$CONTROLLER" "$GROUP" "$RULE_LINE" > "$RULE_FILE"
    if udevadm verify --help >/dev/null 2>&1 && ! udevadm verify "$RULE_FILE" >/dev/null 2>&1; then
        udevadm verify "$RULE_FILE" || true
        rm -f "$RULE_FILE"
        die "udev 规则校验失败，已删除 $RULE_FILE"
    fi
    info "已写入 $RULE_FILE"

    printf '# Generated by setup_k3_gpio.sh: allow group %s to use realtime scheduling for servo pulses\n%s\n' \
        "$GROUP" "$LIMITS_LINE" > "$LIMITS_FILE"
    info "已写入 $LIMITS_FILE"

    udevadm control --reload-rules
    udevadm trigger --subsystem-match=gpio --action=add
    udevadm settle --timeout=10 || true
    info ""

    check || die "安装后检查未通过，见上方缺失项"
    info ""
    info "注意：已经打开的终端看不到新加的组，需要重新登录；SSH 新会话和重启后自动生效。"
    info "用 systemd 运行服务时，组和实时调度要在服务单元里配置（SupplementaryGroups=$GROUP、LimitRTPRIO=$RTPRIO）。"
}

uninstall() {
    [ "$(id -u)" -eq 0 ] || die "撤销需要 root：sudo $0 --uninstall"
    rm -f "$RULE_FILE" "$LIMITS_FILE"
    info "已删除 $RULE_FILE 和 $LIMITS_FILE"
    if [ -n "$(group_gid)" ]; then
        gpasswd -d "$TARGET_USER" "$GROUP" >/dev/null 2>&1 || true
        info "已把 $TARGET_USER 移出 $GROUP 组"
        if [ -z "$(group_members)" ]; then
            groupdel "$GROUP"
            info "组 $GROUP 已无成员，已删除"
        fi
    fi
    udevadm control --reload-rules
    info "现有 /dev/gpiochip* 的权限重启后恢复为 root 独占。"
}

MODE=install
TARGET_USER=${SUDO_USER:-$(id -un)}
while [ $# -gt 0 ]; do
    case "$1" in
        --check) MODE=check ;;
        --uninstall) MODE=uninstall ;;
        --user) shift; [ $# -gt 0 ] || die "--user 需要用户名"; TARGET_USER=$1 ;;
        -h|--help) sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) die "未知参数 $1，见 $0 --help" ;;
    esac
    shift
done
[ "$TARGET_USER" != root ] || [ "$MODE" = check ] || die "要授权的是普通用户，请用 sudo 从普通用户执行，或加 --user NAME"

case "$MODE" in
    install) install ;;
    check) check ;;
    uninstall) uninstall ;;
esac
